import { useCallback, useEffect, useState } from "react";
import { api, ApiError } from "../api/client";
import type { EvaluationRun, ModelVersion } from "../api/types";
import { BarList } from "../components/Charts";
import { Icon } from "../components/Icons";
import { Badge, Card, Empty, ErrorState, InfoNote, Loading, PageHeader, Tabs, useToast } from "../components/UI";
import { dateTime, percent, titleize } from "../utils/format";

interface AnomalyHealth {
  status: string;
  artifact_path: string;
  version: string | null;
  reason: string | null;
  training_rows: number | null;
  feature_version?: string;
  features?: string[];
  contamination?: number;
  registered_models?: Array<{ name: string; version: string; training_rows: number | null; is_active: boolean }>;
}

function MetricGrid({ metrics }: { metrics: Record<string, unknown> }) {
  const entries = Object.entries(metrics || {});
  if (entries.length === 0) return <div className="small muted">No metrics recorded.</div>;
  return (
    <div className="grid grid-4" style={{ gap: 8 }}>
      {entries.map(([key, value]) => (
        <div key={key} className="card stat" style={{ padding: "10px 12px" }}>
          <div className="stat-label" style={{ fontSize: 10 }}>{titleize(key)}</div>
          <div className="stat-value" style={{ fontSize: 18 }}>
            {typeof value === "number" ? (Number.isInteger(value) ? value : value.toFixed(3)) : typeof value === "object" ? JSON.stringify(value).slice(0, 40) : String(value)}
          </div>
        </div>
      ))}
    </div>
  );
}

export default function ModelEvaluationPage() {
  const [tab, setTab] = useState<"runs" | "models" | "anomaly" | "method">("runs");
  const [runs, setRuns] = useState<EvaluationRun[] | null>(null);
  const [models, setModels] = useState<ModelVersion[] | null>(null);
  const [health, setHealth] = useState<AnomalyHealth | null>(null);
  const [selectedRun, setSelectedRun] = useState<EvaluationRun | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const toast = useToast();

  const load = useCallback(() => {
    setRuns(null);
    Promise.all([
      api.get<{ items: EvaluationRun[] }>("/evaluation/runs"),
      api.get<{ items: ModelVersion[] }>("/evaluation/models"),
      api.get<AnomalyHealth>("/evaluation/anomaly/health"),
    ]).then(([runRes, modelRes, healthRes]) => {
      setRuns(runRes.items);
      setModels(modelRes.items);
      setHealth(healthRes);
      setSelectedRun((current) => current || runRes.items[0] || null);
      setError(null);
    }).catch((err) => setError(err.message));
  }, []);

  useEffect(load, [load]);

  const train = async () => {
    setBusy(true);
    try {
      const result = await api.post<{ version: string; training_rows: number; note: string }>("/evaluation/train-anomaly");
      toast.push(`Model ${result.version} trained on ${result.training_rows} invoices.`, "success");
      load();
    } catch (err) {
      toast.push(err instanceof ApiError ? err.message : "Training failed", "error");
    } finally {
      setBusy(false);
    }
  };

  if (error) return <ErrorState message={error} onRetry={load} />;
  if (!runs || !models || !health) return <Loading label="Loading evaluation data" />;

  return (
    <div className="stack">
      <PageHeader
        eyebrow="Administration"
        title="Model evaluation"
        subtitle="Offline, reproducible evaluation of extraction, duplicate detection, fuzzy matching and anomaly ranking on the labelled synthetic dataset."
        actions={
          <>
            <button className="btn" onClick={load}><Icon name="refresh" /> Refresh</button>
            <button className="btn primary" onClick={train} disabled={busy}><Icon name="play" /> {busy ? "Training…" : "Retrain anomaly model"}</button>
          </>
        }
      />

      <InfoNote tone="info">
        <strong>Read this before quoting any number.</strong> Every metric below is measured on synthetic documents generated by {" "}
        <span className="mono">scripts/synthgen.py</span>. They demonstrate that the pipeline behaves correctly on known ground truth; they are not a claim about accuracy on real-world invoices.
      </InfoNote>

      <Tabs
        active={tab}
        onChange={setTab}
        tabs={[
          { id: "runs", label: "Evaluation runs", count: runs.length },
          { id: "models", label: "Model registry", count: models.length },
          { id: "anomaly", label: "Anomaly model" },
          { id: "method", label: "Method & limitations" },
        ]}
      />

      {tab === "runs" && (
        <div className="split-wide">
          <Card title="Runs" subtitle="Newest first" tight>
            {runs.length === 0 ? <Empty title="No evaluation runs" message="Run python -m ml.evaluation.run --count 120 to generate the report and register a run." icon="model" /> : (
              <div>
                {runs.map((run) => (
                  <button
                    key={run.id}
                    onClick={() => setSelectedRun(run)}
                    style={{ display: "block", width: "100%", textAlign: "left", border: 0, borderBottom: "1px solid #eef1f5", padding: "11px 14px", background: selectedRun?.id === run.id ? "var(--primary-soft)" : "transparent", cursor: "pointer" }}
                  >
                    <div className="row"><span className="strong small">{run.name}</span><span className="spacer" /><Badge tone={run.is_synthetic ? "teal" : "warning"}>{run.is_synthetic ? "synthetic" : "live"}</Badge></div>
                    <div className="tiny muted" style={{ marginTop: 3 }}>{run.type} · {run.dataset_size} documents · {dateTime(run.created_at)}</div>
                    <div className="row" style={{ marginTop: 4, gap: 10 }}>
                      <span className="tiny">Overall {run.overall_score !== null ? run.overall_score.toFixed(3) : "—"}</span>
                      <span className="tiny muted">{Object.keys(run.metrics || {}).length} metrics</span>
                    </div>
                  </button>
                ))}
              </div>
            )}
          </Card>
          <div className="stack">
            {selectedRun ? (
              <>
                <Card title={selectedRun.name} subtitle={`${selectedRun.type} · ${selectedRun.dataset} · ${selectedRun.dataset_size} documents`}>
                  <div className="row wrap" style={{ gap: 8 }}>
                    <Badge tone={selectedRun.is_synthetic ? "teal" : "warning"}>{selectedRun.is_synthetic ? "Synthetic evaluation" : "Non-synthetic"}</Badge>
                    {selectedRun.overall_score !== null && <Badge tone="info">Overall {selectedRun.overall_score.toFixed(3)}</Badge>}
                    <span className="tag">{dateTime(selectedRun.created_at)}</span>
                  </div>
                  {selectedRun.notes && <p className="small muted" style={{ marginTop: 10 }}>{selectedRun.notes}</p>}
                  {selectedRun.report_path && <div className="tiny mono muted" style={{ marginTop: 8 }}>{selectedRun.report_path}</div>}
                </Card>
                <Card title="Metrics" subtitle="Computed by ml/evaluation/metrics.py against scenario labels">
                  <MetricGrid metrics={selectedRun.metrics} />
                </Card>
                <Card title="Metric breakdown">
                  <div className="grid grid-2">
                    <div>
                      <div className="tiny muted" style={{ marginBottom: 6 }}>Scores (higher is better)</div>
                      <BarList
                        items={Object.entries(selectedRun.metrics)
                          .filter(([, value]) => typeof value === "number" && Number(value) >= 0 && Number(value) <= 1)
                          .map(([key, value]) => ({ label: titleize(key), value: Number(value) * 100, hint: percent(Number(value)) }))}
                        max={100}
                        labelWidth={190}
                      />
                    </div>
                    <div>
                      <div className="tiny muted" style={{ marginBottom: 6 }}>Error rates (lower is better)</div>
                      <BarList
                        items={Object.entries(selectedRun.metrics)
                          .filter(([key, value]) => typeof value === "number" && /(cer|wer|rate|error)/i.test(key) && Number(value) <= 1)
                          .map(([key, value]) => ({ label: titleize(key), value: Number(value) * 100, hint: percent(Number(value)), color: "#d97706" }))}
                        max={100}
                        labelWidth={190}
                      />
                    </div>
                  </div>
                </Card>
              </>
            ) : <Card><Empty title="Select a run" message="Choose an evaluation run to inspect its metrics." icon="model" /></Card>}
          </div>
        </div>
      )}

      {tab === "models" && (
        <Card title="Model registry" subtitle="Every registered model version, its training size and its metrics" tight>
          {models.length === 0 ? <Empty title="No registered models" message="Train the anomaly model to register the first version." icon="model" /> : (
            <div className="table-wrap">
              <table className="data">
                <thead><tr><th>Name</th><th>Version</th><th>Algorithm</th><th className="num">Rows</th><th>Metrics</th><th>Active</th><th>Trained</th></tr></thead>
                <tbody>
                  {models.map((model) => (
                    <tr key={model.id}>
                      <td><div className="cell-main">{model.name}</div><div className="cell-sub">{model.purpose}</div></td>
                      <td className="mono tiny">{model.version}</td>
                      <td className="small">{model.algorithm}</td>
                      <td className="num tabular">{model.training_rows ?? "—"}</td>
                      <td className="tiny mono" style={{ maxWidth: 280 }}>{JSON.stringify(model.metrics).slice(0, 120)}</td>
                      <td>{model.is_active ? <Badge tone="success">Active</Badge> : <Badge tone="neutral">Retired</Badge>}</td>
                      <td className="tiny muted">{dateTime(model.trained_at)}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </Card>
      )}

      {tab === "anomaly" && (
        <div className="grid grid-2">
          <Card title="Anomaly model status" subtitle="Isolation Forest over vendor-relative invoice features">
            <div className="row" style={{ gap: 10 }}>
              <span className={`health-dot ${health.status === "ok" ? "ok" : health.status === "unavailable" ? "unavailable" : "error"}`} />
              <div>
                <div className="strong">{titleize(health.status)}</div>
                <div className="tiny muted">{health.reason || "Artifact loaded and ready to score."}</div>
              </div>
            </div>
            <div className="divider" />
            <div className="kv">
              <dt>Version</dt><dd className="mono">{health.version || "—"}</dd>
              <dt>Training rows</dt><dd>{health.training_rows ?? "—"}</dd>
              <dt>Feature version</dt><dd className="mono">{health.feature_version || "feature-v1"}</dd>
              <dt>Features</dt><dd>{health.features?.length ?? 18}</dd>
              <dt>Artifact</dt><dd className="tiny mono" style={{ wordBreak: "break-all" }}>{health.artifact_path}</dd>
            </div>
            {health.reason && <InfoNote tone="warning">{health.reason}</InfoNote>}
          </Card>
          <Card title="Feature set" subtitle="Built from invoice, vendor history and extraction quality">
            <div className="row wrap" style={{ gap: 6 }}>
              {(health.features || []).map((feature) => <span className="tag" key={feature}>{feature}</span>)}
            </div>
            <div className="divider" />
            <p className="small muted">The model is retrained on demand. Scores are converted to a percentile within the tenant's training distribution; only the top decile adds risk points, and never more than 25 points.</p>
          </Card>
          <Card title="Retraining" subtitle="Requires at least 30 historical invoices">
            <p className="small muted">Training uses only persisted invoice records for this tenant. The artifact and a JSON sidecar are written atomically; the previous version is retired but kept in the registry.</p>
            <button className="btn primary" style={{ marginTop: 12 }} onClick={train} disabled={busy}><Icon name="play" /> {busy ? "Training…" : "Train now"}</button>
          </Card>
          <Card title="Honest limitations">
            <ul className="small muted" style={{ paddingLeft: 18, margin: 0, lineHeight: 1.8 }}>
              <li>Unsupervised: the model has no fraud labels and cannot be interpreted as a fraud probability.</li>
              <li>Vendor-relative features require history; new vendors receive the neutral baseline.</li>
              <li>Contamination is a hyperparameter (8%), not a measured fraud prevalence.</li>
              <li>Performance is evaluated by ranking known injected anomalies, not by real-world recall.</li>
            </ul>
          </Card>
        </div>
      )}

      {tab === "method" && (
        <div className="stack">
          <Card title="Evaluation protocol">
            <ol className="small" style={{ paddingLeft: 18, lineHeight: 1.9, color: "var(--ink-2)" }}>
              <li>Generate a labelled synthetic dataset with a fixed seed; the generator records the scenario and ground-truth fields for every document.</li>
              <li>Run the real ingestion and processing pipeline end to end — no shortcuts or precomputed extraction.</li>
              <li>Compare OCR text with the generator's source text for CER/WER; compare extracted fields with ground truth for exact-match accuracy.</li>
              <li>Score duplicate detection against injected duplicates and their controls; report precision and recall.</li>
              <li>Score the anomaly model by ranking known injected anomalies (precision@K, recall@K, average position).</li>
              <li>Write the report to <span className="mono">reports/</span> and register an evaluation run with the metrics and the dataset size.</li>
            </ol>
          </Card>
          <div className="grid grid-2">
            <Card title="What is measured">
              <div className="kv">
                <dt>OCR</dt><dd>CER, WER, field exact-match</dd>
                <dt>Extraction</dt><dd>Per-field accuracy, average confidence, calibration</dd>
                <dt>Duplicates</dt><dd>Precision, recall, F1 on injected duplicates</dd>
                <dt>Matching</dt><dd>Rule-level correctness vs expected outcome</dd>
                <dt>Anomaly</dt><dd>Precision@K, recall@K, mean rank</dd>
              </div>
            </Card>
            <Card title="What is not measured">
              <ul className="small muted" style={{ paddingLeft: 18, margin: 0, lineHeight: 1.8 }}>
                <li>Accuracy on real invoices (no real corpus is included).</li>
                <li>Financial loss prevented, which requires production outcomes.</li>
                <li>Adversarial evasion or model drift over time.</li>
                <li>Latency at production scale (measured only on this single-node demo).</li>
              </ul>
            </Card>
          </div>
        </div>
      )}
    </div>
  );
}
